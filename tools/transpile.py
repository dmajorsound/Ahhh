# roomservice JSFX -> C++ transpiler driver
#   python3 transpile.py <in.jsfx> <outdir>
import sys, os, json, re
sys.setrecursionlimit(200000)
import parseall, eelgen
from eelgen import cident

def cstr(s):
    out = []
    for ch in s.encode('utf-8'):
        c = chr(ch)
        if c == '\\': out.append('\\\\')
        elif c == '"': out.append('\\"')
        elif 32 <= ch < 127: out.append(c)
        else: out.append('\\%03o' % ch)
    return '"' + ''.join(out) + '"'

def parse_header(path):
    """slider lines, desc, in/out pins"""
    sliders = []
    desc = ''; pins = [0, 0]
    for line in open(path, encoding='utf-8'):
        if line.startswith('@'): break
        if line.startswith('in_pin:'): pins[0] += 1
        if line.startswith('out_pin:'): pins[1] += 1
        m = re.match(r'slider(\d+):([^<]*)<([^>]*)>(.*)', line)
        if m:
            idx = int(m.group(1)); default = float(m.group(2).split(':')[-1]) if m.group(2).strip() else 0.0
            rng = m.group(3); label = m.group(4).strip()
            hidden = label.startswith('-')
            label = label.lstrip('-')
            enums = None
            mm = re.match(r'([^,]*),([^,]*),([^{]*)(\{(.*)\})?', rng)
            lo, hi, step = float(mm.group(1)), float(mm.group(2)), float(mm.group(3) or 0)
            if mm.group(5) is not None: enums = mm.group(5).split(',')
            sliders.append(dict(idx=idx, default=default, lo=lo, hi=hi, step=step, label=label, hidden=hidden, enums=enums))
        if line.startswith('desc:'): desc = line[5:].strip()
    return desc, sliders, pins

def main(src, outdir):
    os.makedirs(outdir, exist_ok=True)
    secs, funcs, trees = parseall.load(src)
    for f in funcs.values(): eelgen.slider_automate_fix(f.body)
    for t in trees.values(): eelgen.slider_automate_fix(t)
    G = eelgen.Gen(funcs)
    fcode = []; npro = 0
    G.temps = eelgen.temp_globals(funcs, trees, G.fglob)
    def tdecl():
        d = ', '.join('t_%s = 0.0' % cident(v) for v in sorted(G.used_temps)); G.used_temps = set()
        return 'double ' + d + '; ' if d else ''
    for name in sorted(funcs):
        f = funcs[name]
        G.scope = set(f.params) | set(f.locals); G.fname = name
        G.promoted = eelgen.promotable(f) if f.body is not None else set()
        npro += len(G.promoted)
        body = G.v(f.body) if f.body is not None else '0.0'
        params = ', '.join('double %s' % ('l_' + cident(p) if p in G.promoted else 'p%d' % i) for i, p in enumerate(f.params))
        assigns = ' '.join('L_%s_%s = p%d;' % (cident(name), cident(p), i) for i, p in enumerate(f.params) if p not in G.promoted)
        decl = ', '.join('l_%s = 0.0' % cident(v) for v in sorted(set(f.locals) & G.promoted - set(f.params)))
        if decl: assigns = 'double ' + decl + '; ' + assigns
        assigns = tdecl() + assigns
        fcode.append((name, 'double Gen::F_%s(%s) {\n  %s\n  return %s;\n}\n' % (cident(name), params, assigns, body)))
        for v in sorted(G.scope - G.promoted): G.fmembers.append('L_%s_%s' % (cident(name), cident(v)))
        G.promoted = set()
    G.scope = None; G.fname = None
    scode = {}
    for sec in ('init', 'block', 'sample', 'serialize', 'gfx', 'slider'):
        if sec in trees and trees[sec] is not None:
            code = G.v(trees[sec])
            scode[sec] = 'void Gen::S_%s() {\n  %s\n  (void)(%s);\n}\n' % (sec, tdecl(), code)
        else:
            scode[sec] = 'void Gen::S_%s() {}\n' % sec
    # header
    h = ['// GENERATED by transpile.py from %s - do not edit\n#pragma once\n#include "rt.h"\nnamespace rs {\n' % os.path.basename(src),
         'struct Gen : Runtime {\n']
    for gname in sorted(G.globals): h.append('  double g_%s = 0;\n' % cident(gname))
    for m in G.fmembers: h.append('  double %s = 0;\n' % m)
    for name in sorted(funcs):
        h.append('  double F_%s(%s);\n' % (cident(name), ', '.join('double' for _ in funcs[name].params)))
    for sec in scode: h.append('  void S_%s() override;\n' % sec)
    h.append('  void initStrings() override;\n')
    h.append('};\n}\n')
    open(os.path.join(outdir, 'gen.h'), 'w').write(''.join(h))
    # strings
    s = ['// GENERATED\n#include "gen.h"\nnamespace rs {\nvoid Gen::initStrings() {\n']
    for lit, i in sorted(G.lits.items(), key=lambda x: x[1]): s.append('  setLiteral(%d, %s);\n' % (i, cstr(lit)))
    for nm, i in sorted(G.strs.items(), key=lambda x: x[1]): s.append('  setString(%d, "");\n' % i)
    s.append('}\n')
    s.append('\n'.join(scode.values()))
    s.append('}\n')
    open(os.path.join(outdir, 'gen_sections.cpp'), 'w').write(''.join(s))
    # functions in chunks
    chunk = []; size = 0; k = 0
    def flush():
        nonlocal chunk, size, k
        if not chunk: return
        open(os.path.join(outdir, 'gen_f%02d.cpp' % k), 'w').write('// GENERATED\n#include "gen.h"\nnamespace rs {\n' + '\n'.join(chunk) + '}\n')
        k += 1; chunk = []; size = 0
    for name, code in fcode:
        chunk.append(code); size += len(code)
        if size > 250000: flush()
    flush()
    desc, sliders, pins = parse_header(src)
    m = ['// GENERATED\n#include "meta.h"\nnamespace rs {\nconst char* kDesc = %s;\nconst SliderInfo kSliders[] = {\n' % cstr(desc)]
    for sd in sliders:
        m.append('  {%d, %s, %s, %s, %s, %s, %s, %s},\n' % (sd['idx'], eelgen.cnum(sd['default']), eelgen.cnum(sd['lo']), eelgen.cnum(sd['hi']),
                 eelgen.cnum(sd['step']), cstr(sd['label']), 'true' if sd['hidden'] else 'false',
                 cstr('|'.join(sd['enums'])) if sd['enums'] else 'nullptr'))
    m.append('};\nconst int kNumSliders = %d;\nconst int kNumInPins = %d;\nconst int kNumOutPins = %d;\n}\n' % (len(sliders), pins[0] or 2, pins[1] or 2))
    open(os.path.join(outdir, 'gen_meta.cpp'), 'w').write(''.join(m))
    json.dump(dict(desc=desc, sliders=sliders, in_pins=pins[0] or 2, out_pins=pins[1] or 2, strings={k: v for k, v in G.strs.items() if not k.startswith('#tmp')}),
              open(os.path.join(outdir, 'meta.json'), 'w'), indent=1)
    print('globals %d, locals %d, funcs %d, literals %d, strings %d, files %d' % (
        len(G.globals), len(G.fmembers), len(funcs), len(G.lits), len(G.strs), k))
    print('locals moved to registers: %d, globals held in registers inside loops: %d, temporary globals: %d' % (npro, G.ncached, len(G.temps)))
    print('warnings', dict(G.warn))

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
